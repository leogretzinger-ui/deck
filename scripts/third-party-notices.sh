#!/usr/bin/env bash
# Regenerate Go module notices from the packages linked into Deck's Linux binaries.
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 - "$@" <<'PY'
import argparse
import json
import os
from pathlib import Path
import re
import subprocess

parser = argparse.ArgumentParser(description="Regenerate the Go section in THIRD_PARTY_NOTICES.md (requires Go and Python 3).")
parser.add_argument("--check", action="store_true", help="fail if the committed section differs")
args = parser.parse_args()


def go(*args, env=None):
    return subprocess.check_output(["go", *args], env=env, text=True)


def packages():
    for arch in ("amd64", "arm64"):
        for cgo, targets in (
            ("1", ["./cmd/noisedeck"]),
            ("0", ["./cmd/noisedeck-provision", "./cmd/noisedeck-harness-bump", "./cmd/task-workload-latch"]),
        ):
            env = dict(os.environ, GOOS="linux", GOARCH=arch, CGO_ENABLED=cgo)
            data = go("list", "-deps", "-json", *targets, env=env)
            decoder = json.JSONDecoder()
            while data.strip():
                package, end = decoder.raw_decode(data.lstrip())
                data = data.lstrip()[end:]
                yield package


def spdx(name, text):
    normalized = " ".join(text.lower().split())
    licenses = []
    if "permission is hereby granted, free of charge" in normalized:
        licenses.append("MIT")
    if "redistribution and use in source and binary forms" in normalized:
        licenses.append("BSD-3-Clause" if "neither the name" in normalized else "BSD-2-Clause")
    if re.search(r"permission to use, copy, modify, and(?:/or)? distribute", normalized):
        licenses.append("ISC")
    if "apache license" in normalized:
        licenses.append("Apache-2.0")
    if "mozilla public license" in normalized and "2.0" in normalized:
        licenses.append("MPL-2.0")
    if not licenses:
        raise SystemExit(f"Unrecognized license in {name}; review its SPDX identifier before regenerating")
    return licenses


def notice_files(directory):
    return sorted(p for p in directory.iterdir() if p.is_file() and
                  re.fullmatch(r"(?:LICEN[CS]E|COPYING|NOTICE|COPYRIGHT)(?:[.-].*)?", p.name, re.I))


def copyrights(text):
    return set(re.findall(r"^\s*(?://|/\*|\*)?\s*((?:Portions )?Copyright\s+(?:\(c\)|\d{4})[^\n]*)", text, re.M))


modules = {}
for package in packages():
    module = package.get("Module")
    if not module or module.get("Main"):
        continue
    if module.get("Replace"):
        raise SystemExit("Module replacements require a source and license review")
    key = (module["Path"], module["Version"])
    entry = modules.setdefault(key, {"root": Path(module["Dir"]), "dirs": set(), "sources": set()})
    directory = Path(package["Dir"])
    entry["dirs"].add(directory)
    for field in ("GoFiles", "CgoFiles", "CFiles", "HFiles", "SFiles"):
        entry["sources"].update(directory / name for name in package.get(field, []))

begin = "<!-- BEGIN GENERATED GO MODULE NOTICES -->"
end = "<!-- END GENERATED GO MODULE NOTICES -->"
section = [begin, "## Go modules", """Generated by [scripts/third-party-notices.sh](scripts/third-party-notices.sh).
Run `scripts/third-party-notices.sh` to regenerate, or add `--check` to verify
without writing (Go and Python 3 required). Do not edit this section by hand.

This lists the union of third-party modules imported by `cmd/noisedeck`
(with cgo), `cmd/noisedeck-provision`, `cmd/noisedeck-harness-bump` and
`cmd/task-workload-latch` (without cgo), for Linux amd64 and arm64.
Versions and license files come from Go's module cache; package-specific
licenses, complete license headers and NOTICE files are included. Copyright
lines are collected from those notices and the compiled source files. The main module is excluded.
SPDX identifiers describe each module's included licenses. Apache-2.0's
full text below also applies to the Apache-licensed portions of yaml.v3."""]
for (path, version), entry in sorted(modules.items()):
    root = entry["root"]
    if not any(p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING")) for p in notice_files(root)):
        go("mod", "download", path + "@" + version)
    files = set(notice_files(root))
    if not any(p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING")) for p in files):
        raise SystemExit(f"No license found for {path}@{version}")
    for directory in entry["dirs"]:
        while directory != root:
            files.update(notice_files(directory))
            directory = directory.parent
    texts = [(p.relative_to(root).as_posix(), p.read_text()) for p in sorted(files)]
    identifiers = set()
    for name, text in texts:
        if Path(name).name.upper().startswith(("LICENSE", "LICENCE", "COPYING")):
            identifiers.update(spdx(f"{path}/{name}", text))
    holders = set()
    for _, text in texts:
        holders.update(copyrights(text))
    for source in sorted(entry["sources"]):
        source_text = source.read_text()
        holders.update(copyrights(source_text))
        # Some packages put a complete license in a Go header instead of a LICENSE file.
        if source.suffix == ".go":
            header = re.split(r"^package ", source_text, maxsplit=1, flags=re.M)[0]
            for comment in re.findall(r"(?:^//[^\n]*(?:\n|$))+|/\*.*?\*/", header, re.M | re.S):
                notice = re.sub(r"^\s*(?://|/\*|\*/?|\*) ?", "", comment, flags=re.M).strip()
                if re.search(r"Permission (?:is hereby granted|to use, copy)|Redistribution and use", notice):
                    name = source.relative_to(root).as_posix() + " (license header)"
                    identifiers.update(spdx(f"{path}/{name}", notice))
                    if not any(notice == text for _, text in texts):
                        texts.append((name, notice))
    if not holders:
        raise SystemExit(f"No copyright lines found for {path}@{version}")
    section += [f"### {path}", f"Version: `{version}`\n\nSPDX: `{' AND '.join(sorted(identifiers))}`",
                f"[Source](https://proxy.golang.org/{''.join('!' + c.lower() if c.isupper() else c for c in path)}/@v/{version}.zip)",
                "Copyright notices:\n\n```text\n" + "\n".join(sorted(holders)) + "\n```"]
    for name, text in texts:
        section.append(f"`{name}`:\n\n```text\n{text.rstrip()}\n```")
section.append(end)
generated = "\n\n".join(section) + "\n"
file = Path("THIRD_PARTY_NOTICES.md")
original = file.read_text()
if begin in original:
    start = original.index(begin)
    stop = original.index(end, start) + len(end)
    updated = original[:start] + generated.rstrip("\n") + original[stop:]
else:
    updated = original.rstrip() + "\n\n" + generated
if args.check:
    if updated != original:
        raise SystemExit("Go module notices are stale; run scripts/third-party-notices.sh")
    print(f"Go module notices match ({len(modules)} modules)")
else:
    file.write_text(updated)
    print(f"Generated Go module notices ({len(modules)} modules)")
PY
